const split = (value: string): string[] =>
  value
    .split("|")
    .map((part) => part.trim())
    .filter(Boolean);
const slug = (value: string): string =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

export const vocabularyBank: VocabularyEntry[] = Object.entries(topics).flatMap(
  ([topic, rows]) =>
    rows.map(
      ([
        word,
        meaning,
        definition,
        partOfSpeech,
        ipa,
        cefr,
        collocations,
        examples,
        family,
        commonError,
        synonyms,
        register,
      ]) => ({
        id: `vocab-${slug(topic)}-${slug(word)}`,
        word,
        meaning,
        definition,
        partOfSpeech,
        ipa,
        cefr,
        topic,
        collocations: split(collocations),
        examples: split(examples),
        family: split(family),
        commonError,
        synonyms: split(synonyms),
        register,
      }),
    ),
);
